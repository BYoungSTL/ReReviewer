// API ответил 403: роли не хватает. Роли записаны в токене, поэтому новая роль начинает действовать после повторного входа.
export function NoAccess({ role }: { role: string }) {
  return (
    <p className="text-muted-foreground">
      Этот раздел доступен только {role}. Если роль выдали недавно, выйдите и войдите снова.
    </p>
  );
}
